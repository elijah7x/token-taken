#!/usr/bin/env python3
"""Regenerate TokenTakenKit/PriceSnapshot.swift from the newest engine snapshot.

Prices ship inside the app, so this script never touches the network: a maintainer refreshes
`engine/price-snapshot-*.json` before a release and regenerates the Swift table from it.

    python3 scripts/update-prices.py           # rewrite PriceSnapshot.swift
    python3 scripts/update-prices.py --check   # exit 1 if the committed file is stale
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ENGINE_DIR = ROOT / "engine"
OUTPUT = ROOT / "TokenTakenKit" / "PriceSnapshot.swift"


def newest_snapshot():
    snapshots = sorted(ENGINE_DIR.glob("price-snapshot-*.json"))
    if not snapshots:
        raise SystemExit("no engine/price-snapshot-*.json found")
    return snapshots[-1]


def swift_number(value):
    """Format one rate; a null in the JSON becomes `nil`, which means unpriced rather than free."""
    return "nil" if value is None else repr(float(value))


def cache_write_1h(key, entry):
    """Anthropic publishes 1-hour cache writes at 2x the input rate. Every other provider has no
    1-hour tariff, so the rate stays null and those tokens are billed at the cache-write rate."""
    if not key.startswith("claude-") or entry["input"] is None:
        return None
    return entry["input"] * 2


def render(snapshot_path):
    data = json.loads(snapshot_path.read_text(encoding="utf-8"))
    relative = snapshot_path.relative_to(ROOT).as_posix()
    rows = "\n".join(
        '            "%s": Rates(input: %s, cacheRead: %s, cacheWrite: %s, cacheWrite1h: %s, output: %s),'
        % (
            key,
            swift_number(entry["input"]),
            swift_number(entry["cacheRead"]),
            swift_number(entry["cacheWrite"]),
            swift_number(cache_write_1h(key, entry)),
            swift_number(entry["output"]),
        )
        for key, entry in sorted(data["rates"].items())
    )
    return """// Generated from {path} by scripts/update-prices.py. Do not edit this file by hand: edit the
// JSON and regenerate. The JSON is the reviewed source of truth and also records which priced key
// and dataset each model id matched (matchedKey, source) and which categories were left unpriced.
//
// Regenerate from the repository root:
//
//   python3 scripts/update-prices.py
//
// Rates are USD per 1M tokens. A null in the JSON becomes nil here, which marks that category
// unpriced for the model instead of free. `cacheWrite1h` is not in the JSON: it is derived for
// Anthropic Claude models as 2x the input rate and is nil for every other provider.

extension PriceTable {{
    /// Rates from {path}, read with the alias table named in the version.
    public static let bundled = PriceTable(
        version: "{version}" + "+alias-" + PriceTable.aliasTableVersion,
        rates: [
{rows}
        ]
    )
}}
""".format(path=relative, version=data["version"], rows=rows)


def main(argv):
    if argv not in ([], ["--check"]):
        raise SystemExit("usage: update-prices.py [--check]")
    snapshot = newest_snapshot()
    text = render(snapshot)
    output = OUTPUT.relative_to(ROOT).as_posix()
    if argv:
        try:
            committed = OUTPUT.read_text(encoding="utf-8")
        except FileNotFoundError:
            committed = None
        if committed != text:
            print("%s is stale; run python3 scripts/update-prices.py" % output, file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(text, encoding="utf-8")
    print("Wrote %s from %s" % (output, snapshot.relative_to(ROOT).as_posix()))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
